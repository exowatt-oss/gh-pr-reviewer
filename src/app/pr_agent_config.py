REVIEW_OUTPUT_RULES = """\
## Output rules (mandatory)
- Report only real issues in the changed code: bugs, security problems, missing error
  handling, broken conventions with a real cost. No praise, no summaries, no fluff.
- For every issue give `path:line`, a severity (critical | major | minor), what goes wrong, and
  a concrete fix. Start each key issue header with its severity in brackets, e.g.
  `[major] Endpoint missing auth dependency`.
- Order issues by severity: every critical and major issue comes before any minor one; never
  leave out a critical or major issue to make room for a minor one.
- Check the change against the rest of the codebase when context is given below: a new route
  missing a guard its siblings have, a query missing a filter the other queries in the file
  apply, or a literal spelled differently from the module's own constants is a real bug.
- Documentation changes are reviewed too: every command, task name, path, port and env var
  must match the repository (task runner and code context below), and docs must not
  contradict the repo's own stated rules. Report misspellings as a single minor issue listing
  each `wrong -> right`.
- Every issue needs a realistic trigger in how this code is actually deployed and used; skip
  speculative hardening that needs an unusual environment or contrived input.
- Do not repeat what linters/formatters already enforce. Do not invent issues to fill space.
- If there is nothing worth reporting, say "No issues found." That is a fine outcome.
"""


def is_requirements_txt(path: str) -> bool:
    return bool(_REQUIREMENTS_RE.search(path))


def looks_pip_compiled(text: str) -> bool:
    head = (text or "")[:2048].lower()
    return any(marker in head for marker in _PIP_COMPILE_MARKERS)


@lru_cache(maxsize=4)
def _read_style_guide(path: str) -> str:
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError:
        logger.warning("Style guide not found at %s; using output rules only", path)
        return ""
    return text[:STYLE_GUIDE_MAX_CHARS]


def load_style_guide(settings: Settings) -> str:
    return _read_style_guide(settings.STYLE_GUIDE_PATH)


def truncate(text: str, limit: int) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "\n\n[... truncated ...]"


def reviewable_filter(extra_ignore_globs: list[str] | None = None) -> Callable[[str], bool]:
    """``path -> True`` when PR-Agent will send the file to the model (same rules as
    ``pr_agent.algo.file_filter.filter_ignored`` with our ``[ignore]`` settings)."""
    globs = IGNORE_GLOBS + list(extra_ignore_globs or [])
    patterns = [re.compile(r) for r in IGNORE_REGEX]
    for pattern in globs:
        patterns.append(re.compile(fnmatch.translate(pattern)))
        if pattern.startswith("**/"):  # PR-Agent also matches root-level files
            patterns.append(re.compile(fnmatch.translate(pattern[3:])))
    return lambda path: bool(path) and not any(p.match(path) for p in patterns)


MAX_LISTED_EXCLUDED_FILES = 40


def excluded_files_note(paths: list[str]) -> str:
    """Name changed files the model does not see, so it does not report them as missing."""
    if not paths:
        return ""
    shown = sorted(paths)[:MAX_LISTED_EXCLUDED_FILES]
    more = len(paths) - len(shown)
    lines = "\n".join(f"- `{p}`" for p in shown) + (f"\n- … and {more} more" if more else "")
    return (
        "## Changed files not shown in the diff\n\n"
        "This PR also changes these files; they are excluded from the diff (lockfiles, "
        "generated, data or binary files). They are part of the change: never report them as "
        "missing or not updated.\n\n" + lines
    )


def compose_extra_instructions(
    style_guide: str,
    repo_conventions: dict[str, str],
    base_ref: str,
    codebase_context: str = "",
    excluded_files: list[str] | None = None,
    *,
    output_rules: bool = True,
) -> str:
    """Reviewer instructions: output rules (PR-Agent's format only), house rubric, the repo's
    own conventions, then bounded codebase context (full touched files, siblings, task
    runner)."""
    parts = [REVIEW_OUTPUT_RULES] if output_rules else []
    if style_guide.strip():
        parts.append(style_guide.strip())
    if repo_conventions:
        budget = REPO_CONVENTIONS_MAX_CHARS
        sections = []
        for name, text in repo_conventions.items():
            if budget <= 0:
                break
            body = truncate(text, budget)
            budget -= len(body)
            sections.append(f"### {name}\n\n{body}")
        parts.append(
            f"## Repository-specific conventions (from `{base_ref}`; these override the "
            "house rubric where they conflict)\n\n" + "\n\n".join(sections)
        )
    if excluded_files:
        parts.append(excluded_files_note(excluded_files))
    if codebase_context.strip():
        parts.append(codebase_context.strip())
    return "\n\n".join(parts)


def build_overrides(
    settings: Settings,
    *,
    private_key_pem: str,
    extra_instructions: str,
    extra_ignore_globs: list[str] | None = None,
) -> dict[str, Any]:
    """Flat ``section.key -> value`` overrides applied to PR-Agent's settings."""
    model = f"openai/{settings.LLM_MODEL}"
    api_base = settings.LLM_API_BASE.strip().rstrip("/")
    if api_base and not api_base.endswith("/v1"):
        api_base = f"{api_base}/v1"
    return {
        # Use the configured OpenAI-compatible model endpoint without implicit fallbacks.
        "config.model": model,
        "config.model_weak": model,
        "config.model_reasoning": model,
        "config.fallback_models": [],
        "config.reasoning_effort": settings.LLM_REASONING_EFFORT or None,
        "config.custom_reasoning_model": False,
        # Opt reasoning-capable model IDs into the provider's reasoning parameter contract.
        "config.additional_reasoning_effort_models": [settings.LLM_MODEL]
        if settings.LLM_REASONING_EFFORT
        else [],
        "config.no_temperature_models": [settings.LLM_MODEL, model]
        if settings.LLM_REASONING_EFFORT
        else [],
        "config.custom_model_max_tokens": settings.LLM_MAX_CONTEXT_TOKENS,
        "config.max_model_tokens": settings.LLM_MAX_CONTEXT_TOKENS,
        # Bound each provider request; the poller applies its own bounded retry policy.
        "config.ai_timeout": settings.llm_client_timeout_seconds,
        # don't retry the same timed-out call; the poller may retry the whole review later
        "config.retry_same_model_on_timeout": False,
        # no hidden client-side retries either (they would replay a provider timeout as a 500);
        # PR-Agent's own same-model retry still covers other transient errors
        "config.num_retries": 0,
        "openai.key": settings.LLM_API_KEY.get_secret_value(),
        "openai.api_base": api_base or None,
        "litellm.custom_llm_provider": "openai",
        # behaviour
        "config.git_provider": "github",
        "config.publish_output": not settings.DRY_RUN,
        "config.publish_output_progress": False,
        "config.is_auto_command": True,
        "config.use_repo_settings_file": False,
        "config.use_global_settings_file": False,
        "config.enable_per_directory_settings": False,
        "config.extra_config_url": "",
        # repo CLAUDE.md / AGENTS.md go into extra_instructions instead (bounded, base branch)
        "config.repo_context_files": [],
        "config.output_run_details": False,
        "config.output_run_cost": False,
        "config.enable_custom_labels": False,
        "config.log_level": settings.LOG_LEVEL.upper(),
        "config.ignore_pr_authors": [],
        "pr_reviewer.extra_instructions": extra_instructions,
        "pr_reviewer.persistent_comment": True,
        "pr_reviewer.final_update_message": False,
        "pr_reviewer.enable_review_labels_security": False,
        "pr_reviewer.enable_review_labels_effort": False,
        "pr_reviewer.require_score_review": False,
        "pr_reviewer.require_can_be_split_review": False,
        "pr_reviewer.require_security_review": True,
        "pr_reviewer.require_tests_review": True,
        "pr_reviewer.require_estimate_effort_to_review": True,
        "pr_reviewer.enable_help_text": False,
        # PR-Agent marks a run "partial" (findings cannot be auto-resolved) when it returns
        # num_max_findings issues; at 6 the cap was crowding out real defects.
        "pr_reviewer.num_max_findings": NUM_MAX_FINDINGS,
        "pr_reviewer.publish_output_no_suggestions": True,
        "pr_reviewer.minimal_commits_for_incremental_review": 0,
        "pr_reviewer.minimal_minutes_for_incremental_review": 0,
        "pr_description.publish_labels": False,
        "pr_code_suggestions.committable_code_suggestions": False,
        "pr_code_suggestions.extra_instructions": extra_instructions,
        "pr_code_suggestions.enable_help_text": False,
        # [ignore]
        "ignore.glob": IGNORE_GLOBS + list(extra_ignore_globs or []),
        "ignore.regex": list(IGNORE_REGEX),
        # GitHub App auth for PR-Agent's own PyGithub client
        "github.deployment_type": "app",
        "github.app_id": int(settings.GITHUB_APP_ID) if settings.GITHUB_APP_ID.isdigit() else 0,
        "github.private_key": private_key_pem,
        "github.base_url": settings.GITHUB_API_URL.rstrip("/"),
        "github.publish_as_check_run": False,
    }


def apply_overrides(pr_settings: Any, overrides: dict[str, Any]) -> Any:
    for key, value in overrides.items():
        pr_settings.set(key, copy.deepcopy(value))
    return pr_settings


def fresh_pr_agent_settings(overrides: dict[str, Any]) -> Any:
    """A deep copy of PR-Agent's global settings with our overrides applied."""
    from pr_agent.config_loader import global_settings

    return apply_overrides(copy.deepcopy(global_settings), overrides)
